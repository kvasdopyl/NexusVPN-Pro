"""CI helper: stamp build number + repository into the program and the .exe version resource.
Usage: python tools/make_build_info.py <build_number> <owner/repo>
Prints the full version (e.g. 2.1.0.17) for the installer."""
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
build, repo = int(sys.argv[1]), sys.argv[2]
version = re.search(r'APP_VERSION = "([\d.]+)"', (root / "nexusvpn/paths.py").read_text("utf-8")).group(1)
(root / "nexusvpn/build_info.py").write_text(
    f'# Generated by tools/make_build_info.py\nREPO = "{repo}"\nBUILD = {build}\n', "utf-8")
major, minor, patch = (int(x) for x in version.split("."))
vi = (root / "version_info.txt").read_text("utf-8")
vi = re.sub(r"filevers=\([^)]*\)", f"filevers=({major}, {minor}, {patch}, {build})", vi)
vi = re.sub(r"prodvers=\([^)]*\)", f"prodvers=({major}, {minor}, {patch}, {build})", vi)
vi = re.sub(r"'(File|Product)Version', '[^']*'", rf"'\1Version', '{version}.{build}'", vi)
(root / "version_info.txt").write_text(vi, "utf-8")
print(f"{version}.{build}")
